// Стиль заголовков "как у Lary" — строчные буквы заменяются на юникодные
// маленькие капители, заглавные и остальные символы не трогаем (первая
// буква слова обычно и так заглавная, что даёт характерный вид "Sᴋɪᴘᴘᴇᴅ").
// Работает только для латиницы — в Unicode нет блока маленьких капителей
// для кириллицы, поэтому применять эту функцию к русскому тексту бессмысленно.
const SMALL_CAPS_MAP = {
  a: 'ᴀ', b: 'ʙ', c: 'ᴄ', d: 'ᴅ', e: 'ᴇ', f: 'ꜰ', g: 'ɢ', h: 'ʜ', i: 'ɪ',
  j: 'ᴊ', k: 'ᴋ', l: 'ʟ', m: 'ᴍ', n: 'ɴ', o: 'ᴏ', p: 'ᴘ', q: 'q', r: 'ʀ',
  s: 's', t: 'ᴛ', u: 'ᴜ', v: 'ᴠ', w: 'ᴡ', x: 'x', y: 'ʏ', z: 'ᴢ',
};

function toSmallCaps(text) {
  return text.replace(/[a-z]/g, (letter) => SMALL_CAPS_MAP[letter]);
}

module.exports = { toSmallCaps };
